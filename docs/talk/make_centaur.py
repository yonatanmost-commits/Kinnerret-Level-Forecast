"""
make_centaur.py - slide 3, "Centaur": the Old Centaur teased by Eros, in the Louvre.

Originator, 20 Oct: a centaur that speaks the deck's colours, then "the full image in the center"
(their mock-up). The photo (Wikimedia Commons, "Centaur & Cupid, Louvre Museum.jpg", by Wilfredo
Rodriguez, CC BY-SA 2.0, which asks for the credit line) is cream marble in a cream hall. It sits
whole and centred between the title rule and the bottom rule, its edges fading softly into the
page. The title is the show's ("Centaur", build_show.py), like every other slide's.

23 Oct (originator: "another go on the centaur photo"): an illustration made for the talk in
Gemini, in the deck's colours: a centaur playing chess against a laptop on a terrace above the
Kinneret, a football in the grass. images/centaur_gemini_raw.jpeg is Gemini's file (1376 x 768);
make() white-balances its paper to the theme's page, flattens the paper texture, and scales it to
cover the slide (images/centaur_gemini.png). The drawing starts below the title band. The Louvre
photo is kept as draw_louvre().

Run:  python docs/talk/make_centaur.py        # -> charts/centaur_slide.png, 1920 x 1080
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import theme as T                                                    # noqa: E402

PHOTO = HERE / "images" / "centaur_louvre.jpg"
OUT = HERE / "charts" / "centaur_slide.png"
CREDIT = "Old Centaur teased by Eros, Louvre  ·  Photo: Wilfredo Rodriguez, CC BY-SA 2.0"
TOP, BOTTOM = T.TITLE_BAND, T.BOTTOM_RULE["y"] - 24      # the photo's room between the two rules
FEATHER = 40                                             # its soft edge, px


RAW = HERE / "images" / "centaur_gemini_raw.jpeg"
ART = HERE / "images" / "centaur_gemini.png"
ART_CREDIT = "Illustration: generated by Claude Code with Google Gemini"   # originator, 23 Oct


def make() -> Path:
    """Gemini's picture in the theme: its paper becomes the page colour, the slide's size."""
    import numpy as np
    im = Image.open(RAW).convert("RGB")
    a = np.asarray(im).astype(float)
    paper = np.median(a[:120].reshape(-1, 3), axis=0)              # the empty top of the picture
    page = np.array([int(T.SURFACE[i:i + 2], 16) for i in (1, 3, 5)], float)
    a = np.clip(a * (page / paper), 0, 255)                        # white balance: paper -> page
    w = np.clip((np.abs(a - page).sum(2) - 8) / 20, 0, 1)[..., None]
    a = page + (a - page) * w                                      # near-paper texture -> flat page, softly
    out = Image.fromarray(a.round().astype(np.uint8))
    s = max(T.W / out.width, T.H / out.height)                     # cover the slide
    out = out.resize((round(out.width * s), round(out.height * s)), Image.LANCZOS)
    x0, y0 = (out.width - T.W) // 2, (out.height - T.H) // 2
    out.crop((x0, y0, x0 + T.W, y0 + T.H)).save(ART)
    return ART


def draw(path: Path = OUT) -> Path:
    page = Image.open(make()).convert("RGB")
    L = T.Labels()                                              # the credit is native text in the decks
    # bottom right, on the empty terrace, ending short of the lake icon (bottom left is the horse)
    L.pil("credit", (T.LAKE_ICON["x"] - 40, T.CREDIT_XY[1]), ART_CREDIT, T.CREDIT_PT, False, T.INK_2, "rs")
    L.save_pil(page, path)
    print(f"saved {path.name}")
    return path


def draw_louvre(path: Path = OUT) -> Path:
    im = Image.open(PHOTO).convert("RGB")
    h = BOTTOM - TOP
    im = im.resize((round(im.width * h / im.height), h), Image.LANCZOS)
    mask = Image.new("L", im.size, 0)
    ImageDraw.Draw(mask).rectangle([FEATHER, FEATHER, im.width - FEATHER, im.height - FEATHER], fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(FEATHER / 2))
    page = Image.new("RGB", (T.W, T.H), T.SURFACE)
    page.paste(im, ((T.W - im.width) // 2, TOP), mask)
    L = T.Labels()                                              # the credit is native text in the show
    L.pil("credit", T.CREDIT_XY, CREDIT, T.CREDIT_PT, False, T.INK_2, "ls")  # baseline on the bottom rule's line
    L.save_pil(page, path)
    print(f"saved {path.name}")
    return path


if __name__ == "__main__":
    draw()
